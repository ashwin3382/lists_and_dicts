#Print the names of all students in class `"10B"`.
def student_name(data: dict, section : str = "10B")-> dict:
    student_list = []
    for sec in (data['classes']):
        if sec['class_name'] == section:
            for students_names in (sec['students']):
                student_list.append(students_names['name'])

    return {"student names":student_list}

print(student_name(school))



# Find the total marks obtained by each student across all subjects and all exams.
# Return a dictionary:
# - key = student name
# - value = total marks

def tot_marks(data: dict)-> dict:
    student_dict = {}
    for student in data['classes']:
        for score in student['students']:
            tot = 0
            for k, v in score['records']['scores'].items():
                for mark in v:
                    tot += mark['marks']
            student_dict[score['name']] = tot
    return student_dict

print(tot_marks(school))




#Find all students whose attendance percentage is at least 80%.

#Attendance is stored as a list of `1`s and `0`s.

#Return a list of student names.

def attendance(data: dict, min_attendance: float = .80)-> list:
    attendance_list = []
    for student in data['classes']:
        for score in student['students']:
            tot = 0
            count = 0
            for v in score['records']['attendance']:
                tot += v
                count += 1
            min_attd = tot / count
            if min_attd > min_attendance:
                attendance_list.append(score['name'])
    return attendance_list

print(attendance(school))




#Find the student with the highest average score in English.

#Return:
#- student name
#- average English score rounded to 2 decimals

def eng_avg(data: dict, total_tests: int = 3)-> dict:

    student_dict = {}
    highest = {}
    for student in data['classes']:
        for score in student['students']:
            tot = 0
            for v in score['records']['scores']['english']:
                tot += v['marks']
            avg = round(tot / total_tests, 2)
            student_dict[score['name']] = avg

    for name, avg in student_dict.items():
        if avg == max(student_dict.values()):
            highest[name] = avg
    return highest

print(eng_avg(school))





#Create a nested summary dictionary by class with this structure:

#- key = class name
#- value = dictionary containing:
# - `"topper"`: student with highest total marks in that class
#- `"lowest_attendance"`: student with lowest attendance percentage in that class
#- `"class_average_total_marks"`: average total marks of all students in that class, rounded to 2 decimals
#- `"students_above_600"`: list of student names whose total marks are above 600

def summary(data: dict)-> dict:

    summary_dict = {}
    for student in data['classes']:
        marks_total = {}
        attd_dict = {}
        marks_above_600 = []
        for score in student['students']:
            tot = 0
            for k, v in score['records']['scores'].items():
                for mark in v:
                    tot += mark['marks']
            marks_total[score['name']] = tot
            attd_dict[score['name']] = sum(score['records']['attendance'])

        topper = max(marks_total, key=marks_total.get)

        low_attd = min(attd_dict, key=attd_dict.get)

        avg = round(sum(marks_total.values()) / len(marks_total), 2)

        for name, tot in marks_total.items():
            if tot > 600:
                marks_above_600.append([name])

        summary_dict[student['class_name']] = {'topper' : topper,
                         'lowest attendance' : low_attd,
                         'class_average_total_marks' : avg,
                         'students_above_600' : marks_above_600}
    return summary_dict

print(summary(school))
